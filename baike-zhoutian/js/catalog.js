export const GAL_POLE = [12.85, 27.1];

function norm(v) {
  const m = Math.hypot(v[0], v[1], v[2]);
  return [v[0] / m, v[1] / m, v[2] / m];
}

export function rotAxis(v, n, a) {
  const c = Math.cos(a), s = Math.sin(a);
  const d = n[0] * v[0] + n[1] * v[1] + n[2] * v[2];
  return [
    v[0] * c + (n[1] * v[2] - n[2] * v[1]) * s + n[0] * d * (1 - c),
    v[1] * c + (n[2] * v[0] - n[0] * v[2]) * s + n[1] * d * (1 - c),
    v[2] * c + (n[0] * v[1] - n[1] * v[0]) * s + n[2] * d * (1 - c),
  ];
}

const N = norm(AXIS);
const E1 = [1, 0, 0];
const E2 = [N[1] * 0 - N[2] * 0, N[2] * 1 - N[0] * 0, N[0] * 0 - N[1] * 1];

export function starDir(raH, dec, t) {
  const a = raH / 24 * 2 * Math.PI;
  const d = dec / 180 * Math.PI;
  const cd = Math.cos(d);
  let s = [
    cd * Math.cos(a) * E1[0] + cd * Math.sin(a) * E2[0] + Math.sin(d) * N[0],
    cd * Math.cos(a) * E1[1] + cd * Math.sin(a) * E2[1] + Math.sin(d) * N[1],
    cd * Math.cos(a) * E1[2] + cd * Math.sin(a) * E2[2] + Math.sin(d) * N[2],
  ];
  return rotAxis(s, N, 2 * Math.PI * (t / 86400));
}

export function skyAngle(t) {
  return 2 * Math.PI * (t / 86400);
}

export function galacticPoleDir(t) {
  return starDir(GAL_POLE[0], GAL_POLE[1], t);
}
