/* 《青绿千里》总谱
 *
 * 骨架按余辉（故宫博物院研究员）的「七大组岛链」排：
 *   第 1 组序曲（低）→ 1、2 组之间以小桥相接 → 第 3、4 组之间以长桥相连
 *   → 最高主峰在第 5 组（全卷高潮）→ 第 7 组尾声，江面回到卷首高度（闭环）
 * 每组「将主峰和诸多辅峰组合起来，如同一座座山岛矗立在江边湖畔」。
 *
 * 世界坐标：X = 卷轴（+940 卷首/右 → −940 卷尾/左），Z = 纵深（+ 为近岸），Y = 高（水面 0）。
 * 展卷方向右→左，故分镜自 +X 起。
 */

export const WORLD = {
  x0: -940, x1: 940,          // 1880 格 ≈ 画心横 1191.5 cm → 1 格 ≈ 0.634 cm
  z0: -190, z1: 190,          //  380 格 ≈ 画心纵 51.5 cm → 1 格 ≈ 0.129 cm（纵深放大 4.9 倍，散点透视的直译）
  water: 0,
  CM_PER_VOX: 1191.5 / 1880,
};

/** 卷内位置：把世界 X 换算成画心上的厘米数（自卷首起算） */
export function scrollCm(x) {
  return (WORLD.x1 - x) * WORLD.CM_PER_VOX;
}

/* ---------------------------------------------------------------- 山脊
 * 每组由若干「脊」构成：脊是 XZ 平面上的一条折线，节点带高度与半径。
 * 高度场 = 所有脊贡献的 max（不是 sum）——这样主峰与辅峰各自成形，
 * 脊线相连处自然长出山鞍，正是宋画里「大山大岭」的体块感。
 */
