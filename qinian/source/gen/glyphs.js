export const GLYPH_W = 12;
export const GLYPH_H = G.length;
// col 0..11 left→right, row 0..28 top→bottom
export function glyphAt(col, row) {
  if (row < 0 || row >= GLYPH_H || col < 0 || col >= GLYPH_W) return false;
  return G[row][col] === '#';
}
